#!/usr/bin/env node

import { mkdir, readFile, rename, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_DIR = resolve(SCRIPT_DIR, "..");
const DEFAULT_SOURCE_DIR = join(homedir(), ".pi", "agent", "npm", "node_modules", "pi-subagents", "agents");
const DEFAULT_OUTPUT_DIR = join(REPO_DIR, "configs", "codex", "agents");
const DEFAULT_MODEL = "gpt-5.6-luna";

const ROLES = [
  { name: "scout", sandboxMode: "read-only" },
  { name: "researcher", sandboxMode: "read-only" },
  { name: "worker" },
];

const CODEX_COMPATIBILITY_PROMPT = `You are running as a Codex subagent. The role prompt below is synchronized from the pi-subagents package and remains the behavioral source of truth.

Codex runtime compatibility:
- Preserve the source role's priorities, workflow, quality bar, and output structure.
- Interpret references to Pi as references to Codex.
- Use the closest available Codex tool when the source names a Pi-specific tool. Prefer rg for text search and targeted shell commands for filesystem inspection.
- Return the requested result to the parent agent unless the delegated task explicitly requires writing an artifact.
- When the source mentions contact_supervisor or intercom, use the available Codex collaboration messaging to contact the parent agent. Do not invent unavailable tools.
- Parent instructions and applicable AGENTS.md files take precedence when they conflict with the synchronized prompt.`;

function sanitizeUpstreamText(value) {
  return value.replaceAll("\u2014", "-");
}

function parseYamlScalar(value, field, filePath) {
  const trimmed = value.trim();
  if (!trimmed || trimmed === ">" || trimmed === "|") {
    throw new Error(`${filePath}: ${field} must be a non-empty single-line YAML scalar`);
  }

  if (trimmed.startsWith('"')) {
    try {
      return JSON.parse(trimmed);
    } catch (error) {
      throw new Error(`${filePath}: invalid quoted ${field}: ${error.message}`);
    }
  }

  if (trimmed.startsWith("'") && trimmed.endsWith("'")) {
    return trimmed.slice(1, -1).replaceAll("''", "'");
  }

  return trimmed;
}

export function parseAgentMarkdown(content, filePath = "agent.md") {
  const normalized = content.replaceAll("\r\n", "\n");
  const match = normalized.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!match) {
    throw new Error(`${filePath}: expected YAML frontmatter followed by a prompt body`);
  }

  const fields = new Map();
  for (const line of match[1].split("\n")) {
    if (!line || /^\s/.test(line) || line.trimStart().startsWith("#")) {
      continue;
    }

    const separator = line.indexOf(":");
    if (separator === -1) {
      continue;
    }

    fields.set(line.slice(0, separator).trim(), line.slice(separator + 1));
  }

  const nameValue = fields.get("name");
  const descriptionValue = fields.get("description");
  if (nameValue === undefined || descriptionValue === undefined) {
    throw new Error(`${filePath}: frontmatter must define name and description`);
  }

  const body = match[2].trim();
  if (!body) {
    throw new Error(`${filePath}: prompt body must not be empty`);
  }

  return {
    name: sanitizeUpstreamText(parseYamlScalar(nameValue, "name", filePath)),
    description: sanitizeUpstreamText(parseYamlScalar(descriptionValue, "description", filePath)),
    prompt: sanitizeUpstreamText(body),
  };
}

function tomlString(value) {
  return JSON.stringify(value);
}

export function renderCodexAgent({ agent, model, packageVersion, sourceFile, sandboxMode }) {
  const instructions = `${CODEX_COMPATIBILITY_PROMPT}\n\n${agent.prompt}`;
  const lines = [
    "# Generated by scripts/sync-codex-agents-from-pi-subagents.mjs.",
    `# Source: pi-subagents ${packageVersion}, agents/${sourceFile}`,
    "# Do not edit this file. Regenerate it from the installed package.",
    `name = ${tomlString(agent.name)}`,
    `description = ${tomlString(agent.description)}`,
    `model = ${tomlString(model)}`,
    'model_reasoning_effort = "high"',
  ];

  if (sandboxMode) {
    lines.push(`sandbox_mode = ${tomlString(sandboxMode)}`);
  }

  lines.push(`developer_instructions = ${tomlString(instructions)}`, "");
  return lines.join("\n");
}

export async function syncAgents({ sourceDir, outputDir, model = DEFAULT_MODEL }) {
  const packageJsonPath = resolve(sourceDir, "..", "package.json");
  const packageJson = JSON.parse(await readFile(packageJsonPath, "utf8"));
  if (packageJson.name !== "pi-subagents" || typeof packageJson.version !== "string") {
    throw new Error(`${packageJsonPath}: expected a versioned pi-subagents package`);
  }

  await mkdir(outputDir, { recursive: true });
  const generated = [];

  for (const role of ROLES) {
    const sourceFile = `${role.name}.md`;
    const sourcePath = join(sourceDir, sourceFile);
    const agent = parseAgentMarkdown(await readFile(sourcePath, "utf8"), sourcePath);
    if (agent.name !== role.name) {
      throw new Error(`${sourcePath}: expected agent name ${role.name}, found ${agent.name}`);
    }

    const outputPath = join(outputDir, `${role.name}.toml`);
    const temporaryPath = `${outputPath}.tmp-${process.pid}`;
    const rendered = renderCodexAgent({
      agent,
      model,
      packageVersion: packageJson.version,
      sourceFile,
      sandboxMode: role.sandboxMode,
    });
    await writeFile(temporaryPath, rendered, "utf8");
    await rename(temporaryPath, outputPath);
    generated.push(outputPath);
  }

  return { generated, packageVersion: packageJson.version };
}

function parseArguments(args) {
  const options = {
    sourceDir: DEFAULT_SOURCE_DIR,
    outputDir: DEFAULT_OUTPUT_DIR,
    model: DEFAULT_MODEL,
  };

  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];
    if (argument === "--source" || argument === "--output" || argument === "--model") {
      const value = args[index + 1];
      if (!value) {
        throw new Error(`${argument} requires a value`);
      }
      index += 1;
      if (argument === "--source") options.sourceDir = resolve(value);
      if (argument === "--output") options.outputDir = resolve(value);
      if (argument === "--model") options.model = value;
      continue;
    }

    if (argument === "--help" || argument === "-h") {
      process.stdout.write(`Usage: node scripts/sync-codex-agents-from-pi-subagents.mjs [options]\n\nOptions:\n  --source DIR  pi-subagents agents directory\n  --output DIR  Codex agents output directory\n  --model ID    Model for generated agents (default: ${DEFAULT_MODEL})\n`);
      process.exit(0);
    }

    throw new Error(`unknown argument: ${argument}`);
  }

  return options;
}

async function main() {
  const result = await syncAgents(parseArguments(process.argv.slice(2)));
  process.stdout.write(`Generated ${result.generated.length} Codex agents from pi-subagents ${result.packageVersion}.\n`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  });
}
